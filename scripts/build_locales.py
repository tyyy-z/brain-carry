"""Build static Chinese HTML and demo strings. Python standard library only."""
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]

def build():
    locale = json.loads((ROOT / 'translations/zh-CN.json').read_text(encoding='utf-8'))
    html = (ROOT / 'index.html').read_text(encoding='utf-8')
    # Keep the initial visible file and the live file viewer on one translation source.
    html, matches = re.subn(r'(<div id="demo-body" class="viewer-body">).*?(</div>)',
        lambda match: match[1] + locale['files']['brief']['html'] + match[2], html, count=1, flags=re.S)
    if matches != 1:
        raise ValueError('Could not locate the default demo file')
    for source, translation in sorted(locale['page'].items(), key=lambda pair: len(pair[0]), reverse=True):
        if source not in html:
            raise ValueError(f'English copy changed; update its Chinese translation: {source}')
        html = html.replace(source, translation)
    for source, translation in locale['attributes'].items():
        needle = f'aria-label="{source}"'
        if needle not in html:
            raise ValueError(f'Accessible name changed: {source}')
        html = html.replace(needle, f'aria-label="{translation}"')
    html = html.replace('<html lang="en">', '<html lang="zh-CN">')
    stylesheet = re.search(r'<link rel="stylesheet" href="styles\.css(?:\?[^"]*)?">', html)
    if not stylesheet: raise ValueError('Could not locate the stylesheet')
    html = html.replace(stylesheet[0], '<link rel="preload" href="assets/fonts/noto-sans-sc-subset.woff2" as="font" type="font/woff2" crossorigin>\n  ' + stylesheet[0], 1)
    metadata = locale['metadata']
    html = re.sub(r'<title>.*?</title>', '<title>' + metadata['title'] + '</title>', html)
    for field, key in [('name="description"', 'description'), ('property="og:title"', 'ogTitle'), ('property="og:description"', 'ogDescription')]:
        html = re.sub(r'(<meta ' + field + r' content=")[^"]*(">)', lambda match: match[1] + metadata[key] + match[2], html)
    html = html.replace('rel="canonical" href="https://tyyy-z.github.io/brain-carry/"', 'rel="canonical" href="https://tyyy-z.github.io/brain-carry/zh.html"')
    html = html.replace('property="og:url" content="https://tyyy-z.github.io/brain-carry/"', 'property="og:url" content="https://tyyy-z.github.io/brain-carry/zh.html"')
    html = html.replace('href="zh.html?lang=zh" lang="zh-CN" hreflang="zh-CN" aria-label="Switch to Chinese">中文',
        'href="index.html?lang=en" lang="en" hreflang="en" aria-label="Switch to English">English')
    html = html.replace('Your background and how you like to work.', locale['files']['brief']['caption'])
    (ROOT / 'zh.html').write_text(html, encoding='utf-8', newline='\n')
    runtime = {'ui': locale['ui'], 'files': locale['files']}
    (ROOT / 'i18n.js').write_text('// Generated by scripts/build_locales.py. Edit translations/zh-CN.json.\nwindow.BRAIN_CARRY_ZH = ' + json.dumps(runtime, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8', newline='\n')
    print('Built zh.html and i18n.js from translations/zh-CN.json.')

if __name__ == '__main__':
    build()
